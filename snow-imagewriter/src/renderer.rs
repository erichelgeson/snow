//! Page buffer and rendering for ImageWriter output

use crate::protocol::{CharacterInfo, Position};

/// Output resolution in DPI
pub const OUTPUT_DPI: u32 = 144;

/// A page buffer for accumulating print output
#[derive(Clone)]
pub struct PageBuffer {
    /// Page width in inches
    pub width: f32,
    /// Page height in inches
    pub height: f32,
    /// Pixel buffer (RGBA)
    pub pixels: Vec<u8>,
    /// Width in pixels
    pub pixel_width: u32,
    /// Height in pixels
    pub pixel_height: u32,
    /// Whether any content has been drawn
    has_content: bool,
}

impl PageBuffer {
    /// Create a new page buffer
    pub fn new(width: f32, height: f32) -> Self {
        let pixel_width = (width * OUTPUT_DPI as f32) as u32;
        let pixel_height = (height * OUTPUT_DPI as f32) as u32;
        let pixel_count = (pixel_width * pixel_height) as usize;

        // Initialize with white background
        let mut pixels = vec![255u8; pixel_count * 4];
        for i in 0..pixel_count {
            pixels[i * 4 + 3] = 255; // Alpha = opaque
        }

        Self {
            width,
            height,
            pixels,
            pixel_width,
            pixel_height,
            has_content: false,
        }
    }

    /// Check if page has any content
    pub fn is_empty(&self) -> bool {
        !self.has_content
    }

    /// Set a pixel at inch coordinates
    pub fn set_pixel_at_inches(&mut self, x: f32, y: f32, color: u8) {
        let px = (x * OUTPUT_DPI as f32).round() as i32;
        let py = (y * OUTPUT_DPI as f32).round() as i32;
        self.set_pixel(px, py, color);
    }

    /// Set a pixel at pixel coordinates
    pub fn set_pixel(&mut self, x: i32, y: i32, color: u8) {
        if x < 0 || y < 0 || x >= self.pixel_width as i32 || y >= self.pixel_height as i32 {
            return;
        }

        let (r, g, b) = match color {
            1 => (255, 255, 0), // Yellow
            2 => (255, 0, 0),   // Red
            3 => (0, 0, 255),   // Blue
            _ => (0, 0, 0),     // Black
        };

        let idx = ((y as u32 * self.pixel_width + x as u32) * 4) as usize;
        if idx + 3 < self.pixels.len() {
            self.pixels[idx] = r;
            self.pixels[idx + 1] = g;
            self.pixels[idx + 2] = b;
            self.pixels[idx + 3] = 255;
            self.has_content = true;
        }
    }

    /// Draw a character at the given position
    pub fn draw_character(&mut self, pos: Position, info: &CharacterInfo) {
        let char_width_inches = 1.0 / info.cpi as f32;
        let char_height_inches = 1.0 / 6.0; // Standard 6 LPI height

        // Convert to pixels
        let px = (pos.x * OUTPUT_DPI as f32) as i32;
        let py = (pos.y * OUTPUT_DPI as f32) as i32;
        let char_width_px = (char_width_inches * OUTPUT_DPI as f32) as i32;
        let char_height_px = (char_height_inches * OUTPUT_DPI as f32) as i32;

        // Get the character bitmap
        let bitmap = get_char_bitmap(info.ch);

        // Scale factors for rendering
        let scale_x = char_width_px as f32 / 8.0;
        let scale_y = if info.half_height {
            char_height_px as f32 / 16.0 / 2.0
        } else {
            char_height_px as f32 / 16.0
        };

        // Y offset for super/subscript
        let y_offset = if info.superscript {
            -(char_height_px / 3)
        } else if info.subscript {
            char_height_px / 3
        } else {
            0
        };

        // Render the character
        for (cy, &row_bits) in bitmap.iter().enumerate() {
            for cx in 0..8 {
                if row_bits & (1 << (7 - cx)) != 0 {
                    let dx = (cx as f32 * scale_x) as i32;
                    let dy = (cy as f32 * scale_y) as i32 + y_offset;

                    self.set_pixel(px + dx, py + dy, info.color);

                    // Bold: draw an extra pixel to the right
                    if info.bold {
                        self.set_pixel(px + dx + 1, py + dy, info.color);
                    }

                    // Double strike: draw slightly offset
                    if info.double_strike {
                        self.set_pixel(px + dx, py + dy + 1, info.color);
                    }

                    // Italic: shift right as we go up
                    if info.italic {
                        let italic_offset = ((16 - cy) as f32 * 0.2) as i32;
                        self.set_pixel(px + dx + italic_offset, py + dy, info.color);
                    }
                }
            }
        }

        // Underline
        if info.underline {
            let underline_y = py + char_height_px - 2;
            for dx in 0..char_width_px {
                self.set_pixel(px + dx, underline_y, info.color);
            }
        }

        self.has_content = true;
    }
}

